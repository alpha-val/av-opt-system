@projects_router.post(
    "",
    response_model=ProjectOut,
    status_code=status.HTTP_201_CREATED,
    summary="Create a new project",
    description="Create a new project with name, description, and optional tags.",
)
async def create_project(body: ProjectCreate):
    """
    Create a new project.

    This endpoint creates a new project in the database. The project ID
    is automatically generated by MongoDB.

    Required fields:
    - name: Project name (max 200 chars)
    - global_objective_type: Type of global objective
    - global_objective_target: Target magnitude of change

    Args:
        body: ProjectCreate schema with project data

    Returns:
        ProjectOut: Created project with ID and timestamps

    Raises:
        HTTPException: If validation fails (400) or creation fails (500)
    """
    try:
        # Create project (only name is required, objective fields can be set later)
        logger.info(f"Creating project: {body.name}")
        project = await services.create(body)
        return project
    except ValueError as e:
        # Validation errors from repository
        logger.warning(f"Validation error creating project: {e}")
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e),
        )
    except HTTPException:
        # Re-raise HTTP exceptions
        raise
    except Exception as e:
        logger.error(f"Error creating project: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to create project: {str(e)}",
        )


