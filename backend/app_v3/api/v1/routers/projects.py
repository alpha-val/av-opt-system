@projects_router.post(
    "/{project_id}/upload-files",
    summary="Upload files for a project",
    description="Upload base case documents and tabular data files for a project. Total file size limit is 25MB.",
)
async def upload_project_files(
    project_id: str = Path(..., description="Project ID (MongoDB ObjectId as string)"),
    base_case_files: Optional[List[UploadFile]] = File(None, description="Base case report documents (PDF)"),
    tabular_data_files: Optional[List[UploadFile]] = File(None, description="Tabular data files (PDF, Excel, CSV)"),
):
    """
    Upload files for a project.
    
    This endpoint accepts multiple files for base case documents and tabular data.
    Files are validated for type and total size (25MB limit across all files).
    
    Args:
        project_id: MongoDB ObjectId as string
        base_case_files: List of base case PDF files
        tabular_data_files: List of tabular data files (PDF, Excel, CSV)
        
    Returns:
        Dictionary with uploaded document IDs and processing status
        
    Raises:
        HTTPException: If validation fails (400) or project not found (404)
    """
    try:
        # Validate project exists
        project = await services.get(project_id)
        if not project:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Project not found: {project_id}",
            )
        
        # Validate file types and sizes
        MAX_TOTAL_SIZE = 25 * 1024 * 1024  # 25MB in bytes
        ALLOWED_BASE_CASE_TYPES = ["application/pdf"]
        ALLOWED_TABULAR_TYPES = [
            "application/pdf",
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",  # Excel
            "application/vnd.ms-excel",  # Excel (old)
            "text/csv",
        ]
        
        total_size = 0
        document_ids = []
        
        # Process base case files
        base_case_doc_ids = []
        if base_case_files:
            for file in base_case_files:
                if file.content_type not in ALLOWED_BASE_CASE_TYPES:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Invalid file type for base case: {file.content_type}. Only PDF is allowed.",
                    )
                
                file_bytes = await file.read()
                total_size += len(file_bytes)
                
                if total_size > MAX_TOTAL_SIZE:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Total file size exceeds 25MB limit",
                    )
                
                # Generate document ID (placeholder - actual storage will be implemented later)
                doc_id = str(uuid.uuid4())
                base_case_doc_ids.append(doc_id)
                document_ids.append(doc_id)
                logger.info(f"Uploaded base case file: {file.filename} -> {doc_id}")
        
        # Process tabular data files
        tabular_doc_ids = []
        if tabular_data_files:
            for file in tabular_data_files:
                if file.content_type not in ALLOWED_TABULAR_TYPES:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Invalid file type for tabular data: {file.content_type}. Allowed: PDF, Excel, CSV.",
                    )
                
                file_bytes = await file.read()
                total_size += len(file_bytes)
                
                if total_size > MAX_TOTAL_SIZE:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Total file size exceeds 25MB limit",
                    )
                
                # Generate document ID (placeholder - actual storage will be implemented later)
                doc_id = str(uuid.uuid4())
                tabular_doc_ids.append(doc_id)
                document_ids.append(doc_id)
                logger.info(f"Uploaded tabular data file: {file.filename} -> {doc_id}")
        
        # Validate at least one file of each type
        if not base_case_doc_ids:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="At least one base case document is required",
            )
        if not tabular_doc_ids:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="At least one tabular data file is required",
            )
        
        # Update project with document IDs
        update_patch = ProjectUpdate(
            base_case_documents=base_case_doc_ids,
            tabular_data_documents=tabular_doc_ids,
        )
        updated_project = await services.update(project_id, update_patch)
        
        # Trigger document processing (placeholder)
        # In the future, this will call orchestration service
        orchestration = _get_orchestration_service()
        await orchestration.process_project_documents(
            project_id=project_id,
            global_objective_type=project.global_objective_type,
            global_objective_target=project.global_objective_target,
            base_case_document_ids=base_case_doc_ids,
            tabular_data_document_ids=tabular_doc_ids,
        )
        
        return {
            "project_id": project_id,
            "base_case_documents": base_case_doc_ids,
            "tabular_data_documents": tabular_doc_ids,
            "total_files": len(document_ids),
            "total_size_bytes": total_size,
            "message": "Files uploaded successfully. Processing started.",
        }
        
    except ValueError as e:
        logger.warning(f"Invalid project_id format: {project_id}")
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e),
        )
    except HTTPException:
        raise
    except RuntimeError as e:
        logger.error(f"Orchestration service not initialized: {e}")
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Document processing service not available",
        )
    except Exception as e:
        logger.error(f"Error uploading files for project {project_id}: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to upload files: {str(e)}",
        )


