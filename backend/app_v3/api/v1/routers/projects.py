@projects_router.delete(
    "/{project_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete a project",
    description="Delete a project from the system. This only deletes the project document, not associated data.",
)
async def delete_project(
    project_id: str = Path(..., description="Project ID (MongoDB ObjectId as string)"),
):
    """
    Delete a project.

    This endpoint deletes the project document from the database.
    Note: This does NOT delete associated data (entities, relations, etc.).
    Use the clear_project_data endpoint if you need to clean up related data.

    Args:
        project_id: MongoDB ObjectId as string

    Returns:
        HTTP 204 No Content on success

    Raises:
        HTTPException: If project not found (404) or invalid ID format (400)
    """
    try:
        logger.info(f"Deleting project: {project_id}")
        await services.clear_data(project_id)
        deleted = await services.delete(project_id)

        if not deleted:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Project not found: {project_id}",
            )

        # Return 204 No Content (no response body)
        return None
    except ValueError as e:
        # Invalid ObjectId format
        logger.warning(f"Invalid project_id format: {project_id}")
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e),
        )
    except HTTPException:
        # Re-raise HTTP exceptions (like 404)
        raise
    except Exception as e:
        logger.error(f"Error deleting project {project_id}: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to delete project: {str(e)}",
        )


