"""
Project router for CRUD operations.

This module provides FastAPI endpoints for project management:
- Create, Read, Update, Delete (CRUD) operations
- List all projects
- Clear project data

All endpoints are protected and require authentication (can be added via dependencies).
"""

import logging
from typing import List, Optional
from fastapi import APIRouter, HTTPException, status, Path, Depends, UploadFile, File, Form, Query
from bson.errors import InvalidId
