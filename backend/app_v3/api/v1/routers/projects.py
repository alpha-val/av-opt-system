async def _process_uploaded_files_background(
    job_id: str,
    file_data: List[
        Tuple[bytes, str, str, str]
    ],  # (file_bytes, filename, doc_id, artifact_type)
    project_id: str,
    user_id: str,
    store_in_pinecone: bool,
    process_base_case: bool = False,
):
    """Process uploaded files in background with progress updates.

    Args:
        job_id: Unique job identifier for progress tracking
        file_data: List of tuples (file_bytes, filename, doc_id, artifact_type)
        project_id: Project identifier
        user_id: User identifier
        store_in_pinecone: Whether to store entities in Pinecone
    """
    logger.info(
        f"[Background Task] Starting processing for job {job_id} with {len(file_data)} files"
    )
    
    # Wait briefly to allow WebSocket connection to be established
    # This ensures the frontend receives real-time progress updates
    await asyncio.sleep(0.5)
    logger.info(f"[Background Task] Delay complete, starting actual processing for job {job_id}")
    
    try:
        publisher = get_progress_publisher()
        orchestration = _get_orchestration_service()

        logger.info(
            f"[Background Task] Retrieved publisher and orchestration service for job {job_id}"
        )

        total_files = len(file_data)
        successful = 0
        errors = []

        # Emit start event
        logger.info(f"[Background Task] Publishing start event for job {job_id}")
        publisher.publish(
            job_id,
            ProgressEvent(
                job_id=job_id,
                stage=Stage.PROCESSING,
                status=Status.STARTED,
                progress=0,
                seq=0,
                meta={
                    "project_id": project_id,
                    "total_files": total_files,
                    "current_stage": "Processing uploaded files",
                },
            ),
        )
        logger.info(f"[Background Task] Start event published for job {job_id}")

        # Process each file sequentially
        for idx, (file_bytes, filename, doc_id, artifact_type) in enumerate(
            file_data, 1
        ):
            logger.info(
                f"[Background Task] Processing file {idx}/{total_files}: {filename} (doc_id: {doc_id}, type: {artifact_type})"
            )
            try:
                # Emit file start event
                publisher.publish(
                    job_id,
                    ProgressEvent(
                        job_id=job_id,
                        stage=Stage.PROCESSING,
                        status=Status.IN_PROGRESS,
                        progress=int((idx - 1) / total_files * 100),
                        seq=idx * 2 - 1,
                        meta={
                            "project_id": project_id,
                            "current_file": filename,
                            "file_index": idx,
                            "total_files": total_files,
                            "artifact_type": artifact_type,
                            "current_stage": f"Processing {artifact_type} file {idx} of {total_files}: {filename}",
                        },
                    ),
                )

                if artifact_type == "base_case" and process_base_case:
                    # Process the file
                    logger.info(
                        f"[Background Task] Calling orchestration.process_base_case_file for {filename}"
                    )
                    result = await orchestration.process_base_case_file(
                        file_bytes=file_bytes,
                        filename=filename,
                        file_id=doc_id,
                        project_id=project_id,
                        user_id=user_id,
                        store_in_pinecone=store_in_pinecone,
                    )
                    logger.info(
                        f"[Background Task] Processing complete for {filename}: {result.get('status', 'unknown')}"
                    )
                elif artifact_type == "tabular_data":
                    # Process the file
                    logger.info(
                        f"[Background Task] Calling orchestration.process_tabular_data_file for {filename}"
                    )
                    result = await orchestration.process_tabular_data_file(
                        file_bytes=file_bytes,
                        filename=filename,
                        file_id=doc_id,
                        project_id=project_id,
                        user_id=user_id,
                        store_in_pinecone=store_in_pinecone,
                        job_id=job_id,
                        progress_publisher=publisher,
                    )
                    logger.info(
                        f"[Background Task] Processing complete for {filename}: {result.get('status', 'unknown')}"
                    )
                else:
                    logger.warning(
                        f"[Background Task] Unknown artifact_type '{artifact_type}' for file {filename}, skipping processing"
                    )
                    result = {
                        "status": "skipped",
                        "reason": f"Unknown artifact_type: {artifact_type}",
                    }

                successful += 1

                # Emit file complete event
                publisher.publish(
                    job_id,
                    ProgressEvent(
                        job_id=job_id,
                        stage=Stage.PROCESSING,
                        status=Status.IN_PROGRESS,
                        progress=int(idx / total_files * 100),
                        seq=idx * 2,
                        meta={
                            "project_id": project_id,
                            "current_file": filename,
                            "file_index": idx,
                            "total_files": total_files,
                            "artifact_type": artifact_type,
                            "current_stage": f"Completed {artifact_type} file {idx} of {total_files}",
                            "tables_extracted": result.get("tables_extracted", 0),
                            "entities_extracted": result.get("entities_extracted", 0),
                        },
                    ),
                )

            except Exception as e:
                logger.error(f"Error processing file {filename}: {e}", exc_info=True)
                errors.append(
                    {
                        "filename": filename,
                        "doc_id": doc_id,
                        "error": str(e),
                    }
                )

        # Emit completion event
        final_status = (
            Status.COMPLETED
            if successful == total_files
            else (Status.COMPLETED if successful > 0 else Status.FAILED)
        )

        logger.info(
            f"[Background Task] Processing complete for job {job_id}: {successful}/{total_files} files successful"
        )
        publisher.publish(
            job_id,
            ProgressEvent(
                job_id=job_id,
                stage=(
                    Stage.COMPLETE if final_status == Status.COMPLETED else Stage.ERROR
                ),
                status=final_status,
                progress=100,
                seq=len(file_data) * 2 + 1,
                meta={
                    "project_id": project_id,
                    "total_files": total_files,
                    "successful_files": successful,
                    "failed_files": len(errors),
                    "errors": errors if errors else None,
                    "current_stage": f"Processing complete: {successful}/{total_files} files processed successfully",
                },
            ),
        )

    except Exception as e:
        logger.error(
            f"Background processing failed for job {job_id}: {e}", exc_info=True
        )
        publisher.publish(
            job_id,
            ProgressEvent(
                job_id=job_id,
                stage=Stage.ERROR,
                status=Status.FAILED,
                progress=0,
                seq=999,
                meta={"error": str(e)},
            ),
        )
    finally:
        # Cleanup
        logger.info(f"[Background Task] Cleaning up task for job {job_id}")
        if job_id in _upload_processing_tasks:
            del _upload_processing_tasks[job_id]
            logger.info(
                f"[Background Task] Task removed from tracking for job {job_id}"
            )


@projects_router.post(
    "/{project_id}/upload-files",
    summary="Upload files for a project",
    description="Upload base case documents and tabular data files for a project. Total file size limit is 25MB. Tabular data files will be automatically processed to extract tables and entities.",
)
async def upload_project_files(
    background_tasks: BackgroundTasks,
    project_id: str = Path(..., description="Project ID (MongoDB ObjectId as string)"),
    base_case_files: Optional[List[UploadFile]] = File(
        None, description="Base case report documents (PDF)"
    ),
    tabular_data_files: Optional[List[UploadFile]] = File(
        None, description="Tabular data files (PDF, Excel, CSV)"
    ),
    store_in_pinecone: bool = Query(
        True,
        description="Whether to store extracted entities in Pinecone (default: True)",
    ),
    current_user: dict = Depends(get_current_user),
):
    """
    Upload files for a project.

    This endpoint accepts multiple files for base case documents and tabular data.
    Files are validated for type and total size (25MB limit across all files).

    For tabular data files, the system will automatically:
    - Extract tables from PDF files
    - Extract entities using LLM with MSIO ontology
    - Store tables and entities/edges in MongoDB
    - Store entities in Pinecone by default (can be disabled by setting store_in_pinecone=False)

    Args:
        project_id: MongoDB ObjectId as string
        base_case_files: List of base case PDF files
        tabular_data_files: List of tabular data files (PDF, Excel, CSV)
        store_in_pinecone: Whether to store extracted entities in Pinecone (default: True)
        current_user: Current authenticated user (from JWT token)

    Returns:
        Dictionary with uploaded document IDs, processing status, and processing results

    Raises:
        HTTPException: If validation fails (400) or project not found (404)
    """
    try:
        # Get user_id from authenticated user
        user_id = str(current_user["_id"])

        # Validate project exists
        project = await services.get(project_id)
        if not project:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Project not found: {project_id}",
            )

        # Validate file types and sizes
        MAX_TOTAL_SIZE = 25 * 1024 * 1024  # 25MB in bytes
        ALLOWED_BASE_CASE_TYPES = ["application/pdf"]
        ALLOWED_TABULAR_TYPES = [
            "application/pdf",
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",  # Excel
            "application/vnd.ms-excel",  # Excel (old)
            "text/csv",
        ]

        total_size = 0
        document_ids = []

        # Store file bytes for processing (only PDFs can be processed currently)
        # Combined list: (file_bytes, filename, doc_id, artifact_type)
        files_to_process = []

        # Process base case files
        base_case_doc_ids = []
        if base_case_files:
            file_storage = _get_file_storage_service()
            for file in base_case_files:
                if file.content_type not in ALLOWED_BASE_CASE_TYPES:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Invalid file type for base case: {file.content_type}. Only PDF is allowed.",
                    )

                file_bytes = await file.read()
                total_size += len(file_bytes)

                if total_size > MAX_TOTAL_SIZE:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Total file size exceeds 25MB limit",
                    )

                # Store file in GridFS
                doc_id = file_storage.store_file(
                    file_bytes=file_bytes,
                    filename=file.filename or "unknown.pdf",
                    project_id=project_id,
                    artifact_type="base_case",
                    content_type=file.content_type,
                )
                base_case_doc_ids.append(doc_id)
                document_ids.append(doc_id)
                logger.info(
                    f"Uploaded and stored base case file: {file.filename} -> {doc_id}"
                )

                # Store file data for processing (only PDFs can be processed currently)
                if file.content_type == "application/pdf":
                    files_to_process.append(
                        (
                            file_bytes,
                            file.filename or "unknown.pdf",
                            doc_id,
                            "base_case",
                        )
                    )
                    logger.info(
                        f"Added {file.filename} to processing queue (base_case)"
                    )
                else:
                    logger.info(f"Skipping {file.filename} - not a PDF, cannot process")

        # Process tabular data files
        tabular_doc_ids = []
        if tabular_data_files:
            file_storage = _get_file_storage_service()

            for idx, file in enumerate(tabular_data_files, 1):
                if file.content_type not in ALLOWED_TABULAR_TYPES:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Invalid file type for tabular data: {file.content_type}. Allowed: PDF, Excel, CSV.",
                    )

                file_bytes = await file.read()
                total_size += len(file_bytes)

                if total_size > MAX_TOTAL_SIZE:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Total file size exceeds 25MB limit",
                    )

                # Store file in GridFS
                doc_id = file_storage.store_file(
                    file_bytes=file_bytes,
                    filename=file.filename or "unknown",
                    project_id=project_id,
                    artifact_type="tabular_data",
                    content_type=file.content_type,
                )
                tabular_doc_ids.append(doc_id)
                document_ids.append(doc_id)
                logger.info(
                    f"Uploaded and stored tabular data file: {file.filename} -> {doc_id}"
                )

                # Store file data for processing (only PDFs can be processed currently)
                if file.content_type == "application/pdf":
                    files_to_process.append(
                        (file_bytes, file.filename or "unknown", doc_id, "tabular_data")
                    )
                    logger.info(
                        f"Added {file.filename} to processing queue (tabular_data)"
                    )
                else:
                    logger.info(f"Skipping {file.filename} - not a PDF, cannot process")

        # Validate at least one file was uploaded
        if not document_ids:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="At least one file must be uploaded",
            )

        # Update project with document IDs, merging with existing documents
        update_data = {}
        if base_case_doc_ids:
            # Merge new base case documents with existing ones
            existing_base_case = project.base_case_documents or []
            update_data["base_case_documents"] = list(
                set(existing_base_case + base_case_doc_ids)
            )
        if tabular_doc_ids:
            # Merge new tabular data documents with existing ones
            existing_tabular = project.tabular_data_documents or []
            update_data["tabular_data_documents"] = list(
                set(existing_tabular + tabular_doc_ids)
            )

        # Update project with merged document lists
        update_patch = ProjectUpdate(**update_data)
        updated_project = await services.update(project_id, update_patch)
        logger.info(
            f"Updated project {project_id} with {len(base_case_doc_ids)} base case and {len(tabular_doc_ids)} tabular documents"
        )

        # Process files in background if any PDFs were uploaded
        if files_to_process:
            # Generate unique job ID for background processing
            job_id = str(uuid.uuid4())
            logger.info(
                f"Creating background task for job {job_id} with {len(files_to_process)} files "
                f"({sum(1 for _, _, _, at in files_to_process if at == 'base_case')} base_case, "
                f"{sum(1 for _, _, _, at in files_to_process if at == 'tabular_data')} tabular_data)"
            )

            # Publish start event
            publisher = get_progress_publisher()
            publisher.publish(
                job_id,
                ProgressEvent(
                    job_id=job_id,
                    stage=Stage.PROCESSING,
                    status=Status.STARTED,
                    progress=0,
                    seq=0,
                    meta={
                        "project_id": project_id,
                        "total_files": len(files_to_process),
                        "current_stage": "Processing uploaded files",
                    },
                ),
            )
            logger.info(f"Start event published for job {job_id}")

            # Schedule background task for file processing using FastAPI's BackgroundTasks
            # This ensures the task runs AFTER the response is sent to the client
            background_tasks.add_task(
                _process_uploaded_files_background,
                job_id=job_id,
                file_data=files_to_process,
                project_id=project_id,
                user_id=user_id,
                store_in_pinecone=store_in_pinecone,
            )

            logger.info(
                f"Background task scheduled for {len(files_to_process)} files (job_id: {job_id})"
            )
            logger.info(f"Background task will run after response is sent")

            # Return with job info
            return {
                "job_id": job_id,
                "project_id": project_id,
                "status": "queued",
                "message": "Files uploaded successfully. Processing started in background.",
                "websocket_url": f"/api/v1/ws/progress/{job_id}",
                "base_case_documents": base_case_doc_ids,
                "tabular_data_documents": tabular_doc_ids,
                "total_files": len(document_ids),
                "total_size_bytes": total_size,
            }
        else:
            # No processing needed (no PDFs to process)
            logger.info(f"No PDF files to process. Returning success response.")
            return {
                "project_id": project_id,
                "base_case_documents": base_case_doc_ids,
                "tabular_data_documents": tabular_doc_ids,
                "total_files": len(document_ids),
                "total_size_bytes": total_size,
                "message": "Files uploaded successfully. No processing required.",
            }

    except ValueError as e:
        logger.warning(f"Invalid project_id format: {project_id}")
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e),
        )
    except HTTPException:
        raise
    except RuntimeError as e:
        logger.error(f"Orchestration service not initialized: {e}")
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Document processing service not available",
        )
    except Exception as e:
        logger.error(
            f"Error uploading files for project {project_id}: {e}", exc_info=True
        )
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to upload files: {str(e)}",
        )


